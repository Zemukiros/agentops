"""Seed one `user` and one `reviewer` (ADR-012). Idempotent.

Tokens come from SEED_USER_TOKEN / SEED_REVIEWER_TOKEN. If unset, random tokens are generated
and written to `.agentops-tokens` (mode 0600, gitignored), never to stdout/logs.
Only HMAC hashes are stored in the database. `--rotate` regenerates unset tokens.
"""

from __future__ import annotations

import asyncio
import os
import secrets
import sys
from pathlib import Path

from sqlalchemy import text

from agentops.api.auth import hash_token
from agentops.db.session import make_engine

SEED_USERS = (
    ("demo-user", "user", "SEED_USER_TOKEN"),
    ("demo-reviewer", "reviewer", "SEED_REVIEWER_TOKEN"),
)


async def seed(*, rotate: bool = False) -> dict[str, str]:
    engine = make_engine(pool_size=1)
    created: dict[str, str] = {}
    try:
        async with engine.begin() as conn:
            for name, role, env in SEED_USERS:
                exists = (
                    await conn.execute(text("SELECT 1 FROM users WHERE name = :n"), {"n": name})
                ).first()
                token = os.environ.get(env)
                if exists and not token and not rotate:
                    continue  # keep the existing token
                token = token or secrets.token_urlsafe(32)
                await conn.execute(
                    text(
                        "INSERT INTO users (id, name, token_hash, role) "
                        "VALUES (gen_random_uuid(), :n, :h, CAST(:r AS user_role)) "
                        "ON CONFLICT (name) DO UPDATE SET token_hash = EXCLUDED.token_hash, "
                        "role = EXCLUDED.role"
                    ),
                    {"n": name, "h": hash_token(token), "r": role},
                )
                if not os.environ.get(env):
                    created[name] = token
    finally:
        await engine.dispose()
    return created


TOKENS_FILE = Path(".agentops-tokens")


def write_tokens(tokens: dict[str, str], path: Path = TOKENS_FILE) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("# AgentOps dev API tokens (generated by `make seed`). Do not commit.\n")
        for name, tok in tokens.items():
            f.write(f"{name}={tok}\n")


if __name__ == "__main__":
    new = asyncio.run(seed(rotate="--rotate" in sys.argv))
    if new:
        write_tokens(new)
        print(f"generated tokens for {', '.join(new)}; written to {TOKENS_FILE} (0600)")
    else:
        print("seed users present")
